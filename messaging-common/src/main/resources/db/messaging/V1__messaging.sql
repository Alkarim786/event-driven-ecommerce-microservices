-- Shared by every service (each service still has its OWN database).

-- Transactional outbox: written in the same local transaction as the business change,
-- then published to Kafka by OutboxRelay. seq gives a total order for the relay.
CREATE TABLE outbox (
    seq           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id      UUID         NOT NULL UNIQUE,
    topic         VARCHAR(100) NOT NULL,
    aggregate_id  VARCHAR(64)  NOT NULL,
    event_type    VARCHAR(64)  NOT NULL,
    payload       TEXT         NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at  TIMESTAMP WITH TIME ZONE
);

-- The partial index on unpublished rows is Postgres-only: see db/vendor/postgresql.

-- Idempotent consumer: inserted in the same transaction as the side effect.
-- A duplicate delivery hits the primary key and the whole transaction is rolled back.
CREATE TABLE processed_messages (
    consumer_group VARCHAR(100) NOT NULL,
    event_id       UUID         NOT NULL,
    processed_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (consumer_group, event_id)
);
