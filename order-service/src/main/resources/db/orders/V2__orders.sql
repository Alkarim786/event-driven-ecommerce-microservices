-- order-service owns pricing (catalog) and the order aggregate.

CREATE TABLE catalog (
    sku          VARCHAR(64)  PRIMARY KEY,
    name         VARCHAR(200) NOT NULL,
    price_cents  BIGINT       NOT NULL CHECK (price_cents >= 0)
);

CREATE TABLE orders (
    id               UUID         PRIMARY KEY,
    customer_id      VARCHAR(64)  NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    total_cents      BIGINT       NOT NULL,
    payment_token    VARCHAR(64)  NOT NULL,
    idempotency_key  VARCHAR(100) UNIQUE,
    cancel_reason    VARCHAR(200),
    version          INT          NOT NULL DEFAULT 0,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at     TIMESTAMP WITH TIME ZONE
);

CREATE INDEX orders_customer_idx ON orders (customer_id, created_at);

CREATE TABLE order_items (
    order_id          UUID        NOT NULL REFERENCES orders (id),
    sku               VARCHAR(64) NOT NULL,
    quantity          INT         NOT NULL CHECK (quantity > 0),
    unit_price_cents  BIGINT      NOT NULL,
    PRIMARY KEY (order_id, sku)
);

-- Saga timeline: every event this service saw for the order. Makes the choreography visible.
CREATE TABLE order_timeline (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     UUID         NOT NULL REFERENCES orders (id),
    event_type   VARCHAR(64)  NOT NULL,
    detail       VARCHAR(300),
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX order_timeline_order_idx ON order_timeline (order_id, id);
